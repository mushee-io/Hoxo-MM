import { describe, expect, it } from 'vitest'
import { accrueResearchVaultInterest, applyResearchVaultAction, assertResearchVaultInvariant,
 emptyResearchVault, simulateResearchLiquidation } from './researchLendingVault'
const now=1_797_100_000_000
const price=(value:number,t=now)=>({priceUsdE8:BigInt(value)*100_000_000n,observedAtMs:t,source:'research-fixture' as const})
const usd=(n:number)=>BigInt(n)*100_000_000n
describe('M15–M17 integer-only and off-chain lending lifecycle',()=>{
  it('models separate supplier and collateralized borrower with exact conservation',()=>{
    const fresh=emptyResearchVault()
    const v1=applyResearchVaultAction(fresh,'supplier-a','supply',usd(500))
    const v2=applyResearchVaultAction(v1,'borrower-b','deposit-collateral',10n**9n)
    const v3=applyResearchVaultAction(v2,'borrower-b','borrow',usd(60),price(100),now)
    expect(v3.cashE8).toBe(usd(440))
    expect(v3.debtE8).toBe(usd(60))
    expect(v3.collateralAtomic).toBe(10n**9n)
    expect(v3.accounts['borrower-b'].debtE8).toBe(usd(60))
    expect(v1.debtE8).toBe(0n)
    const interest=accrueResearchVaultInterest(v3,1000)
    expect(interest.debtE8).toBe(usd(66))
    expect(interest.accruedInterestE8).toBe(usd(6))
    assertResearchVaultInvariant(interest)
    const repaid=applyResearchVaultAction(interest,'borrower-b','repay',usd(66))
    expect(repaid.cashE8).toBe(usd(506))
    const withdrawn=applyResearchVaultAction(repaid,'borrower-b','withdraw-collateral',10n**9n,price(100),now)
    const closed=applyResearchVaultAction(withdrawn,'supplier-a','withdraw-supply',usd(500))
    expect(closed.cashE8).toBe(usd(6))
    expect(closed.accruedInterestE8).toBe(usd(6))
    expect(closed.collateralAtomic).toBe(0n)
    expect(closed.settlement).toBe('simulated-only')
    assertResearchVaultInvariant(closed)
  })
  it('refuses unsecured borrow, excess debt, overwithdrawal and stale oracle',()=>{
    const v=applyResearchVaultAction(emptyResearchVault(),'supplier-a','supply',usd(500))
    expect(()=>applyResearchVaultAction(v,'borrower-b','borrow',usd(1),price(100),now)).toThrow(/loan-to-value/)
    const c=applyResearchVaultAction(v,'borrower-b','deposit-collateral',10n**9n)
    expect(()=>applyResearchVaultAction(c,'borrower-b','borrow',usd(71),price(100),now)).toThrow(/loan-to-value/)
    const b=applyResearchVaultAction(c,'borrower-b','borrow',usd(70),price(100),now)
    expect(()=>applyResearchVaultAction(b,'borrower-b','withdraw-collateral',1n,price(100),now)).toThrow(/loan-to-value/)
    expect(()=>applyResearchVaultAction(b,'borrower-b','borrow',usd(1),price(100,now-61000),now)).toThrow(/stale/)
    expect(()=>applyResearchVaultAction(b,'supplier-a','withdraw-supply',usd(500))).toThrow(/Insufficient/)
    expect(()=>applyResearchVaultAction(b,'borrower-b','repay',usd(71))).toThrow(/exceeds/)
    expect(()=>accrueResearchVaultInterest(b,10001)).toThrow()
    expect(()=>assertResearchVaultInvariant({...b,cashE8:b.cashE8+1n})).toThrow(/invariant/)
  })
  it('requires genuine undercollateralisation in research and caps liquidations',()=>{
    let v=applyResearchVaultAction(emptyResearchVault(),'supplier-a','supply',usd(500))
    v=applyResearchVaultAction(v,'borrower-b','deposit-collateral',10n**9n)
    v=applyResearchVaultAction(v,'borrower-b','borrow',usd(70),price(100),now)
    expect(()=>simulateResearchLiquidation(v,'borrower-b',usd(10),price(100),now)).toThrow(/not eligible/)
    const stressed=price(80)
    expect(()=>simulateResearchLiquidation(v,'borrower-b',usd(36),stressed,now)).toThrow(/close factor/)
    const r=simulateResearchLiquidation(v,'borrower-b',usd(30),stressed,now)
    expect(r.vault.debtE8).toBe(usd(40))
    expect(r.vault.cashE8).toBe(usd(460))
    expect(r.seizedCollateralAtomic).toBe(393_750_000n)
    expect(r.execution).toBe('simulated-only')
    assertResearchVaultInvariant(r.vault)
    expect(()=>simulateResearchLiquidation(v,'borrower-b',usd(30),price(80,now-61000),now)).toThrow(/stale/)
  })
})
